/* ---------------- 선택 기록 ---------------- */
export function applyGain(flags, gain) {
  const next = { ...freshFlags(), ...flags }
  AXES.forEach((a) => { if (gain?.[a]) next[a] += gain[a] })
  return next
}

/* 작별(C)은 숨은 결말이라 문턱을 넘어야 열린다.
   문턱을 낮추면 아무나 보게 되어 "숨은" 의미가 없고,
   너무 높이면 끝까지 밀어붙인 사람도 못 봐서 허탈해진다. */
export const FAREWELL_THRESHOLD = 10

export function unlockedEndings(flags) {
  const f = { ...freshFlags(), ...flags }
  const out = ['fusion', 'share']
  if (f.farewell >= FAREWELL_THRESHOLD) out.push('farewell')
  return out
}

/* 지금까지의 선택이 가장 많이 가리키는 방향 (추천 표시용) */
export function leaningEnding(flags) {
  const f = { ...freshFlags(), ...flags }
  const open = unlockedEndings(flags)
  return open.reduce((best, id) => (f[id] > f[best] ? id : best), open[0])
}

