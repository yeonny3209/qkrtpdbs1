/* ==================================================================
   아레나 — "벙커"

   맵 하나가 게임 전부다. 레벨 에디터도 외부 포맷도 없이, 축에 나란한
   상자 목록으로만 정의한다. 축 정렬을 고집하는 이유는 충돌과 레이캐스트
   둘 다 상자-검사 하나로 끝나기 때문이다. 기울어진 벽 하나를 허용하는
   순간 두 시스템 모두 훨씬 복잡해진다.

   좌표는 Three.js 관례를 따른다 — Y 가 위, 바닥은 y=0, XZ 평면이 땅.
   ================================================================== */

export const ARENA = {
  half: 15,          // 30 x 30
  wallHeight: 4.5,
  wallThick: 1,
}

/* 엄폐물 — {x, z} 는 중심, {w, d} 는 전체 너비/깊이, h 는 높이.

   전부 플레이어 점프 높이보다 높다. 위에 올라설 수 있게 하면 수직
   충돌까지 풀어야 하는데, 그러면 바닥 평면 하나로 끝나던 중력 처리가
   "지금 뭘 밟고 있나" 문제로 번진다. 아레나는 평면 하나로 유지한다. */
/* 지나다닐 수 있는 최소 틈. 가장 뚱뚱한 적(브루트, 지름 1.64)이
   여유 있게 통과해야 한다.

   이 값을 지키는 것이 취향 문제가 아니라는 걸 테스트로 확인한다.
   처음 배치에서 중앙 십자의 팔 사이 대각선 틈이 0.57 이었는데,
   플레이어 지름(0.72)보다도 좁았다. 그런 틈에 끼면 밀어내기가
   양쪽에서 번갈아 밀어 수렴하지 못하고, 결국 벽을 뚫고 나간다.
   눈으로는 "좀 좁네" 정도로 보이는 배치가 물리를 깨뜨린 것이다. */
export const MIN_GAP = 2.0

/* 통로 높이와 계단 한 칸의 높이.

   한 칸은 반드시 STEP_HEIGHT(0.45)보다 낮아야 걸어 올라간다.
   통로는 바닥에서 점프해도 못 닿아야 한다 — 닿으면 계단이 장식이
   되고, 계단이라는 길목이 사라진다. */
export const CATWALK_H = 2.0
const STEP_RISE = 0.4
const STEP_RUN = 0.6

/* 계단 한 벌. 낮은 턱을 층층이 쌓은 것이 곧 계단이다.
   from → to 로 x 가 늘어나며 올라간다. */
function stairsUpX(xStart, z, depth, steps = 4) {
  return Array.from({ length: steps }, (_, i) => ({
    x: xStart + STEP_RUN * (i + 0.5),
    z,
    w: STEP_RUN,
    d: depth,
    h: STEP_RISE * (i + 1),
  }))
}

const COVER = [
  /* 중앙 광장을 두르는 벽 넷. 서로 닿지 않게 떨어뜨려 네 귀퉁이에
     대각선 통로를 낸다 — 광장은 사방이 막힌 요새가 아니라 입구가
     네 개인 곳이어야, 한쪽만 보고 버티는 게 답이 되지 않는다.

     통로(2.0)에 올라선 눈높이가 3.62 라, 이 벽은 그보다 높아야
     한다. 낮으면 통로 위에서 광장 안이 훤히 보여 그 자리가 답이
     되어 버린다. 또 통로에서 점프해도 이 위에 못 올라서야 한다. */
  { x: 0, z: -6, w: 6, d: 1.2, h: 3.8 },
  { x: 0, z: 6, w: 6, d: 1.2, h: 3.8 },
  { x: -6, z: 0, w: 1.2, d: 6, h: 3.8 },
  { x: 6, z: 0, w: 1.2, d: 6, h: 3.8 },

  // 네 귀퉁이 기둥 — 구석으로 몰렸을 때 완전히 갇히지 않도록
  // 벽에서 띄워 둔다. 뒤로 돌아 나갈 틈이 남아야 한다.
  { x: -10.5, z: -10.5, w: 2.4, d: 2.4, h: 3.8 },
  { x: 10.5, z: -10.5, w: 2.4, d: 2.4, h: 3.8 },
  { x: -10.5, z: 10.5, w: 2.4, d: 2.4, h: 3.8 },
  { x: 10.5, z: 10.5, w: 2.4, d: 2.4, h: 3.8 },

  /* ── 양쪽 통로 ────────────────────────────────────────────────
     담장에 딱 붙여 놓는다. 띄우면 그 사이에 사람 하나 못 지나가는
     틈이 생기고, 거기 끼면 밀어내기가 수렴하지 못해 벽을 뚫는다.

     계단은 통로 안쪽(광장 쪽)에 하나씩만 둔다. 올라가는 길이
     하나뿐이라 높은 자리가 공짜가 아니다 — 적도 그 길로 올라온다. */
  { x: 13, z: 0, w: 4, d: 8, h: CATWALK_H },
  { x: -13, z: 0, w: 4, d: 8, h: CATWALK_H },
]

/* 계단 — 통로로 이어지는 유일한 길 */
const STAIRS = [
  ...stairsUpX(8.6, 0, 4),      // 동쪽 통로로
  ...stairsUpX(8.6, 0, 4).map((s) => ({ ...s, x: -s.x })),  // 서쪽(대칭)
]

/* 상자를 min/max 형태로 펼친다. 충돌·레이캐스트가 매 프레임 쓰는
   모양이라, 매번 중심에서 계산하지 않고 미리 만들어 둔다. */
function toBox(c) {
  return {
    minX: c.x - c.w / 2, maxX: c.x + c.w / 2,
    minY: 0, maxY: c.h,
    minZ: c.z - c.d / 2, maxZ: c.z + c.d / 2,
    cx: c.x, cz: c.z, w: c.w, d: c.d, h: c.h,
  }
}

/* 바깥 담장 네 짝. 안쪽 면이 정확히 ±half 에 오도록 바깥으로 두께만큼
   밀어 둔다 — 이래야 "아레나는 30x30" 이라는 말이 실제 플레이 공간과
   일치한다. */
function perimeter() {
  const { half: h, wallHeight: wh, wallThick: t } = ARENA
  const span = h * 2 + t * 2
  return [
    { x: 0, z: -(h + t / 2), w: span, d: t, h: wh },
    { x: 0, z: h + t / 2, w: span, d: t, h: wh },
    { x: -(h + t / 2), z: 0, w: t, d: span, h: wh },
    { x: h + t / 2, z: 0, w: t, d: span, h: wh },
  ]
}

export const COVER_BOXES = COVER.map(toBox)
export const STAIR_BOXES = STAIRS.map(toBox)
export const WALL_BOXES = perimeter().map(toBox)

/* 충돌·시야 판정이 쓰는 전체 목록 */
export const ALL_BOXES = [...WALL_BOXES, ...COVER_BOXES, ...STAIR_BOXES]

/* 계단은 "지나갈 수 있는 틈" 규칙에서 뺀다.

   계단 칸끼리는 붙어 있어야 계단이고, 통로와도 붙어 있어야 한다.
   낮은 턱은 애초에 벽이 아니라 밟고 넘는 것이라, 사이에 사람이
   지나갈 틈을 요구하는 것 자체가 말이 안 된다. */
export const GAP_CHECKED_BOXES = [...WALL_BOXES, ...COVER_BOXES]

